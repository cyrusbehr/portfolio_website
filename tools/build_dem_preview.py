#!/usr/bin/env python3
"""Build the quarter-resolution elevation preview that the hero draws on its very first frame.

The full elevation file is about 1 MB, so the hero would otherwise stay empty until it downloads. This script
averages it down 4x4, keeps the same Terrarium encoding (and the water bit in the lowest blue bit), and writes it
as a lossless WebP inlined in a small script. Inlined, it needs no extra request, works from file://, and decodes
straight into the hero's first frame; the full file then morphs in when it arrives.

Usage:
  python3 tools/build_dem_preview.py site/assets/data/austin-dem.v1.webp site/assets/data/austin-dem-q4.v1.js
"""
import base64
import io
import sys

import numpy as np
from PIL import Image

K = 4  # must match PREVIEW_K in site/assets/js/terrain.js


def main(src, out):
    a = np.asarray(Image.open(src).convert('RGB')).astype(np.int64)
    b = a[..., 2]
    h = a[..., 0] * 256 + a[..., 1] + (b & 254) / 256 - 32768
    w = b & 1
    H, W = h.shape[0] // K * K, h.shape[1] // K * K
    hq = h[:H, :W].reshape(H // K, K, W // K, K).mean((1, 3))
    wq = (w[:H, :W].reshape(H // K, K, W // K, K).mean((1, 3)) > 0.5).astype(np.int64)
    v = np.round((hq + 32768) * 4) / 4                     # quarter-metre steps compress well and are plenty
    fl = np.floor(v).astype(np.int64)
    fr = np.clip(np.round((v - fl) * 256).astype(np.int64), 0, 255)
    rgb = np.stack([fl >> 8, fl & 255, (fr & 254) | wq], -1).astype(np.uint8)
    buf = io.BytesIO()
    Image.fromarray(rgb).save(buf, 'WEBP', lossless=True, quality=100, method=6)
    data = base64.b64encode(buf.getvalue()).decode('ascii')
    with open(out, 'w') as f:
        f.write('// Quarter-resolution elevation preview (Terrarium-encoded lossless WebP), generated by tools/build_dem_preview.py.\n')
        f.write(f"window.TerrainPreview = {{ k: {K}, webp: '{data}' }};\n")
    print(f'{rgb.shape[1]}x{rgb.shape[0]}, {len(buf.getvalue()) / 1024:.0f} KB webp, {len(data) / 1024:.0f} KB inlined -> {out}')


if __name__ == '__main__':
    main(*sys.argv[1:3])
