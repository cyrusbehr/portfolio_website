#!/usr/bin/env python3
"""Straighten the hero car's loop where OpenStreetMap routing makes it double back.

build_roads.py stitches the loop from shortest paths between waypoints. At the MoPac / Cesar Chavez interchange by
Lady Bird Lake, MoPac crosses the riverside road on a bridge with no direct ramp in the data, so the stitched path
drove onto the bridge, U-turned, looped through the ramps and U-turned again before heading west. This replaces
that stretch with a plain right turn: down MoPac to where it crosses the riverside road, then west along that road
through its own vertices, rejoining the loop where it already ran west.

Usage:
  python3 tools/fix_route.py site/assets/data/austin-roads.v1.js site/assets/data/austin-roads.v2.js

Run it again after rebuilding the roads with build_roads.py. It refuses to write if the stretch it expects is not
there, and it fails if the result still has any reversal sharper than 150 degrees. Afterwards, regenerate LOOP_PTS
in site/assets/js/terrain.js (it prints the new list).
"""
import json
import math
import sys

MOPAC = (1219.64, 890.09)        # last loop point on MoPac southbound before the interchange
WEST = (1199.73, 899.53)         # first loop point on the riverside road west of MoPac
# The turn, in DEM px: where MoPac's centre line crosses the riverside road, then that road's vertices westward.
TURN = [(1211.4, 902.8), (1210.0, 902.4), (1207.9, 901.8), (1206.5, 901.5), (1205.7, 901.3)]
MPP = 16.494


def turn_deg(a, b, c):
    t = math.atan2(c[1] - b[1], c[0] - b[0]) - math.atan2(b[1] - a[1], b[0] - a[0])
    t -= 2 * math.pi * round(t / (2 * math.pi))
    return abs(math.degrees(t))


def main(src, out):
    text = open(src).read()
    data = json.loads(text[text.index('=') + 1:].strip().rstrip(';'))
    r = data['route']
    pts = [(r[i], r[i + 1]) for i in range(0, len(r), 2)]
    near = lambda p: min(range(len(pts)), key=lambda i: math.dist(pts[i], p))
    i, j = near(MOPAC), near(WEST)
    if math.dist(pts[i], MOPAC) > .5 or math.dist(pts[j], WEST) > .5 or not i < j:
        sys.exit('The loop no longer matches the stretch this fix expects; inspect it before changing anything.')
    pts = pts[:i + 1] + TURN + pts[j:]
    worst = max(turn_deg(pts[k - 1], pts[k], pts[k + 1]) for k in range(1, len(pts) - 1))
    if worst > 150:
        sys.exit(f'A reversal of {worst:.0f} degrees remains; not writing.')
    km = sum(math.dist(p, q) for p, q in zip(pts, pts[1:])) * MPP / 1000
    data['route'] = [round(c, 2) for p in pts for c in p]
    data['routeKm'] = round(km, 2)
    with open(out, 'w') as f:
        f.write("// Roads and the hero car's loop, from OpenStreetMap (ODbL). Generated by tools/build_roads.py and\n")
        f.write('// tools/fix_route.py.\n')
        f.write('window.TerrainRoads = ')
        json.dump(data, f, separators=(',', ':'))
        f.write(';\n')
    loop = ','.join(f'{round(x)},{round(y)}' for x, y in pts[::4])
    print(f'removed {j - i - 1} points, added {len(TURN)}; loop {km:.2f} km, sharpest turn {worst:.0f} deg -> {out}')
    print(f'LOOP_PTS = [{loop}]')


if __name__ == '__main__':
    main(*sys.argv[1:3])
